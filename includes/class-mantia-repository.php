					get_posts(
						array(
							'post_type'      => Mantia_CPTs::MATCH,
							'post_status'    => 'publish',
							'posts_per_page' => 50,
							'no_found_rows'  => true,
							'meta_query'     => array(
								array(
									'key'   => self::META_STATUS,
									'value' => 'finished',
								),
								array(
									'key'     => self::META_RESOLVED,
									'value'   => '1',
									'compare' => '!=',
								),
							),
						)
					)
