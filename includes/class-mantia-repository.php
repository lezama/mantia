	/**
	 * Download an image and attach it to the given mantia_user post as
	 * the featured image (post_thumbnail). The frontend already prefers
	 * the thumbnail over the generated initials avatar, so the moment
	 * openclawp surfaces inbound image messages, hooking into this is
	 * enough to give users their real photo.
	 *
	 * @return int Attachment ID, or 0 on failure.
	 */
	public static function set_user_avatar_from_url( int $user_id, string $image_url, array $request_headers = array() ): int {
		if ( $user_id <= 0 || '' === $image_url ) {
			return 0;
		}
		if ( get_post_type( $user_id ) !== Mantia_CPTs::USER ) {
			return 0;
		}

		$response = wp_remote_get(
			$image_url,
			array(
				'timeout' => 15,
				'headers' => $request_headers, // Meta media URLs need Bearer auth
			)
		);
		if ( is_wp_error( $response ) || 200 !== (int) wp_remote_retrieve_response_code( $response ) ) {
			return 0;
		}

		$body         = (string) wp_remote_retrieve_body( $response );
		$content_type = (string) wp_remote_retrieve_header( $response, 'content-type' );
		$ext          = self::guess_extension_from_content_type( $content_type );
		if ( '' === $ext ) {
			return 0;
		}

		require_once ABSPATH . 'wp-admin/includes/file.php';
		require_once ABSPATH . 'wp-admin/includes/image.php';
		require_once ABSPATH . 'wp-admin/includes/media.php';

		$tmp = wp_tempnam( 'mantia-avatar-' . $user_id . '.' . $ext );
		if ( false === file_put_contents( $tmp, $body ) ) {
			return 0;
		}

		$attachment_id = media_handle_sideload(
			array(
				'name'     => sprintf( 'avatar-%d-%d.%s', $user_id, time(), $ext ),
				'tmp_name' => $tmp,
				'size'     => strlen( $body ),
				'type'     => $content_type,
			),
			$user_id,
			sprintf( 'Avatar for mantia user %d', $user_id )
		);
		if ( is_wp_error( $attachment_id ) ) {
			@unlink( $tmp );
			return 0;
		}

		set_post_thumbnail( $user_id, (int) $attachment_id );
		return (int) $attachment_id;
	}

	private static function guess_extension_from_content_type( string $content_type ): string {
		$content_type = strtolower( trim( explode( ';', $content_type )[0] ) );
		return match ( $content_type ) {
			'image/jpeg', 'image/jpg' => 'jpg',
			'image/png'               => 'png',
			'image/webp'              => 'webp',
			'image/gif'               => 'gif',
			default                   => '',
		};
	}

	/**
	 * Return every user post that has $group_id in its META_GROUP_IDS.
	 * Penca scale is small (<100 members), so full-table scan over the
	 * user CPT is fine and saves us a serialized-meta LIKE hack.
	 *
	 * @return array<int, array{id:int,name:string,phone:string,display_name:string}>
	 */
	public static function group_members( int $group_id ): array {
		if ( $group_id <= 0 ) {
			return array();
		}
		$users = get_posts(
			array(
				'post_type'      => Mantia_CPTs::USER,
				'post_status'    => 'publish',
				'posts_per_page' => -1,
				'no_found_rows'  => true,
			)
		);
		$members = array();
		foreach ( $users as $u ) {
			$groups = (array) get_post_meta( (int) $u->ID, self::META_GROUP_IDS, true );
			if ( ! in_array( $group_id, array_map( 'intval', $groups ), true ) ) {
				continue;
			}
			$title   = (string) get_the_title( (int) $u->ID );
			$phone   = (string) get_post_meta( (int) $u->ID, self::META_PHONE, true );
			$has_name = '' !== $title && $title !== $phone;
			$members[] = array(
				'id'           => (int) $u->ID,
				'name'         => $title,
				'phone'        => $phone,
				'display_name' => $has_name ? $title : __( 'sin nombre', 'mantia' ),
			);
		}
		usort(
			$members,
			static fn( array $a, array $b ): int => strcasecmp( (string) $a['display_name'], (string) $b['display_name'] )
		);
		return $members;
	}

	/**
	 * Return the user's group IDs that belong to a given competition. A
	 * "match" here is at storage_id level: a group in libertadores-semana
	 * (a view) is considered a match for any match in libertadores-2026
	 * (its parent), because the window-views never store matches of their
	 * own — they're just filtered windows over the parent.
	 *
	 * @return array<int,int>
	 */
	public static function user_groups_in_competition( int $user_id, string $competition_id ): array {
		$target = Mantia_Competitions::storage_id( $competition_id );
		$out    = array();
		foreach ( self::user_groups_to_array( $user_id ) as $g ) {
			$group_comp = (string) ( $g['competition_id'] ?? '' );
			$group_root = Mantia_Competitions::storage_id( $group_comp );
			if ( $group_root === $target ) {
				$out[] = (int) $g['id'];
			}
		}
		return $out;
	}

	public static function generate_invite_code( string $name ): string {
		$base = self::normalize_invite_code( $name );
		$base = '' !== $base ? substr( $base, 0, 14 ) : 'MANTIA';

		for ( $attempt = 0; $attempt < 10; ++$attempt ) {
			$suffix = strtoupper( substr( wp_generate_password( 5, false, false ), 0, 5 ) );
			$code   = self::normalize_invite_code( $base . $suffix );
			if ( ! self::find_group_by_invite_code( $code ) ) {
				return $code;
			}
		}

		return self::normalize_invite_code( $base . wp_rand( 10000, 99999 ) );
	}

