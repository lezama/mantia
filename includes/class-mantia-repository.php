	/**
	 * Upsert a prediction.
	 *
	 * @param bool $auto_filled true when the call originates in
	 *   auto_fill_predictions() — sets META_AUTO_FILLED so the /me/
	 *   page can show "your scores are still random" hints. Callers
	 *   from the user-initiated path (WhatsApp parsing, REST endpoint)
	 *   should leave the default false; the upsert clears any prior
	 *   auto-fill flag so editing an auto-fill PR converts it to manual.
	 */
	public static function register_prediction( int $user_id, int $match_id, int $group_id, int $home_score, int $away_score, bool $auto_filled = false ): array|WP_Error {
		$match = self::match_to_array( $match_id );
		if ( empty( $match ) ) {
			return new WP_Error( 'mantia_match_not_found', __( 'No encuentro ese partido.', 'mantia' ) );
		}
		if ( 'scheduled' !== $match['status'] || (int) $match['kickoff_ts'] <= time() ) {
			return new WP_Error( 'mantia_match_closed', __( 'Ese partido ya cerro para pronosticos.', 'mantia' ) );
		}

		$existing = self::find_prediction( $user_id, $match_id, $group_id );
		$title    = sprintf(
			'%s: %s %d-%d %s',
			get_the_title( $user_id ),
			$match['home_team'],
			$home_score,
			$away_score,
			$match['away_team']
		);
		$postarr  = array(
			'post_type'   => Mantia_CPTs::PREDICTION,
			'post_status' => 'publish',
			'post_title'  => $title,
		);

		if ( $existing ) {
			$postarr['ID'] = $existing->ID;
			$post_id       = wp_update_post( $postarr, true );
		} else {
			$post_id = wp_insert_post( $postarr, true );
		}

		if ( is_wp_error( $post_id ) ) {
			return $post_id;
		}

		$post_id = (int) $post_id;
		update_post_meta( $post_id, self::META_USER_ID, $user_id );
		update_post_meta( $post_id, self::META_USER_PHONE, (string) get_post_meta( $user_id, self::META_PHONE, true ) );
		update_post_meta( $post_id, self::META_MATCH_ID, $match_id );
		update_post_meta( $post_id, self::META_GROUP_ID, $group_id );
		update_post_meta( $post_id, self::META_PRED_HOME_SCORE, max( 0, $home_score ) );
		update_post_meta( $post_id, self::META_PRED_AWAY_SCORE, max( 0, $away_score ) );
		update_post_meta( $post_id, self::META_SCORED, 0 );
		// Track origin so /me/ can tell "this user has never edited"
		// from "this user has actively predicted". Manual upserts
		// (default $auto_filled = false) clear any prior auto flag.
		update_post_meta( $post_id, self::META_AUTO_FILLED, $auto_filled ? 1 : 0 );

		return self::prediction_to_array( $post_id );
	}

	/**
	 * Has this user EVER manually predicted anything? True when at
	 * least one of their prediction rows lacks the META_AUTO_FILLED
	 * flag (or has it set to 0). Drives the "your scores are still
	 * random" hint on /me/.
	 */
	public static function user_has_manual_prediction( int $user_id ): bool {
		$found = get_posts(
			array(
				'post_type'      => Mantia_CPTs::PREDICTION,
				'post_status'    => 'publish',
				'posts_per_page' => 1,
				'no_found_rows'  => true,
				'fields'         => 'ids',
				'meta_query'     => array(
					'relation' => 'AND',
					array( 'key' => self::META_USER_ID, 'value' => $user_id ),
					array(
						'relation' => 'OR',
						array( 'key' => self::META_AUTO_FILLED, 'value' => '0' ),
						array( 'key' => self::META_AUTO_FILLED, 'compare' => 'NOT EXISTS' ),
					),
				),
			)
		);
		return ! empty( $found );
	}

	/**
	 * How many points did this user earn from the most recently
	 * finished match in $competition_id (in this $group_id's
	 * leaderboard)? Returns null when there's no finished match yet,
	 * so /me/ can skip the delta line entirely instead of saying
	 * "ganaste 0 pts" with nothing to reference.
	 *
	 * @return array{points:int, match:array}|null
	 */
	public static function last_match_delta( int $user_id, int $group_id ): ?array {
		$competition_id = self::group_competition_id( $group_id );
		$recent         = self::recent_finished_matches_for_competition( $competition_id, 1 );
		if ( empty( $recent ) ) {
			return null;
		}
		$match = $recent[0];
		$pred  = self::find_prediction( $user_id, (int) $match['id'], $group_id );
		$pts   = $pred ? (int) get_post_meta( (int) $pred->ID, self::META_POINTS, true ) : 0;
		return array( 'points' => $pts, 'match' => $match );
	}

	/**
	 * Most recently kicked-off matches for a competition, ordered by
	 * kickoff descending. Used by the consensus command — we want the
	 * one most likely to be the conversation topic.
	 */
	public static function recent_finished_matches_for_competition( string $competition_id, int $limit = 10 ): array {
		$storage_id = Mantia_Competitions::storage_id( $competition_id );
		$posts      = get_posts(
			array(
				'post_type'      => Mantia_CPTs::MATCH,
				'post_status'    => 'publish',
				'posts_per_page' => max( 1, $limit ),
				'meta_key'       => self::META_KICKOFF_TS,
				'orderby'        => 'meta_value_num',
				'order'          => 'DESC',
				'meta_query'     => array(
					'relation' => 'AND',
					array( 'key' => Mantia_Competitions::META_KEY, 'value' => $storage_id ),
					array( 'key' => self::META_KICKOFF_TS, 'value' => time(), 'compare' => '<=', 'type' => 'NUMERIC' ),
				),
			)
		);

		$matches = array();
		foreach ( $posts as $post ) {
			$matches[] = self::match_to_array( (int) $post->ID );
		}
		return $matches;
	}

	/**
	 * Group consensus for a single match: returns a [score_key => count]
	 * map of how the penca's members predicted that match. Hard guard:
	 * returns an empty array if the match hasn't kicked off yet — the
	 * "no one sees another's predictions before kickoff" rule is enforced
	 * here (callers don't have to remember).
	 *
	 * Score keys are formatted "H-A" so the caller can render them flat
	 * ("2-1: 4 jugadores") without re-parsing.
	 *
	 * @return array<string,int>
	 */
	public static function group_consensus_for_match( int $group_id, int $match_id ): array {
		$match = self::match_to_array( $match_id );
		if ( empty( $match ) ) {
			return array();
		}
		// Privacy guard: predictions are private until kickoff.
		if ( (int) $match['kickoff_ts'] > time() ) {
			return array();
		}

		$predictions = get_posts(
			array(
				'post_type'      => Mantia_CPTs::PREDICTION,
				'post_status'    => 'publish',
				'posts_per_page' => -1,
				'no_found_rows'  => true,
				'meta_query'     => array(
					'relation' => 'AND',
					array( 'key' => self::META_GROUP_ID, 'value' => $group_id ),
					array( 'key' => self::META_MATCH_ID, 'value' => $match_id ),
				),
			)
		);

		$consensus = array();
		foreach ( $predictions as $pred ) {
			$home = (int) get_post_meta( (int) $pred->ID, self::META_PRED_HOME_SCORE, true );
			$away = (int) get_post_meta( (int) $pred->ID, self::META_PRED_AWAY_SCORE, true );
			$key  = sprintf( '%d-%d', $home, $away );
			$consensus[ $key ] = ( $consensus[ $key ] ?? 0 ) + 1;
		}
		// Sort by count desc so the caller can take the head row as the
		// "majority pick" without resorting.
		arsort( $consensus );
		return $consensus;
	}

	public static function find_prediction( int $user_id, int $match_id, int $group_id ): ?WP_Post {
		$posts = get_posts(
			array(
				'post_type'      => Mantia_CPTs::PREDICTION,
				'post_status'    => 'publish',
				'posts_per_page' => 1,
				'no_found_rows'  => true,
				'meta_query'     => array(
					array(
						'key'   => self::META_USER_ID,
						'value' => $user_id,
					),
					array(
						'key'   => self::META_MATCH_ID,
						'value' => $match_id,
					),
					array(
						'key'   => self::META_GROUP_ID,
						'value' => $group_id,
					),
				),
			)
		);

		return $posts[0] ?? null;
	}

	public static function prediction_to_array( int $prediction_id ): array {
		$post = get_post( $prediction_id );
		if ( ! $post || Mantia_CPTs::PREDICTION !== $post->post_type ) {
			return array();
		}

		return array(
			'id'          => $prediction_id,
			'user_id'     => (int) get_post_meta( $prediction_id, self::META_USER_ID, true ),
			'user_phone'  => (string) get_post_meta( $prediction_id, self::META_USER_PHONE, true ),
			'match_id'    => (int) get_post_meta( $prediction_id, self::META_MATCH_ID, true ),
			'group_id'    => (int) get_post_meta( $prediction_id, self::META_GROUP_ID, true ),
			'home_score'  => (int) get_post_meta( $prediction_id, self::META_PRED_HOME_SCORE, true ),
			'away_score'  => (int) get_post_meta( $prediction_id, self::META_PRED_AWAY_SCORE, true ),
			'points'      => (int) get_post_meta( $prediction_id, self::META_POINTS, true ),
			'reason'      => (string) get_post_meta( $prediction_id, self::META_SCORING_REASON, true ),
			'scored'      => (bool) get_post_meta( $prediction_id, self::META_SCORED, true ),
			'user_name'   => get_the_title( (int) get_post_meta( $prediction_id, self::META_USER_ID, true ) ),
		);
	}

